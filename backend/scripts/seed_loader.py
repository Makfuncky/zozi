"""Single SQL-seed loader for ZOZI (dev/legacy offline utility).

Loads seed rows from the **canonical Python module**
``infrastructure/database/seed/_seed_constants.py`` and writes them via raw
SQL to a local SQLite database. The same Python constants are mirrored to
the ``seed_data/*_full.json`` files (regenerated by
``scripts/regen_seed_json.py``) so any downstream tool that still reads the
JSON keeps working. New code should use the canonical Python module.

The **production** seed path is ``infrastructure.database.seed._common.seed_data()``
which inserts directly into the Neon PostgreSQL tables via SQLAlchemy ORM.
This script is a dev-only offline tool and is deprecated for production use.

Usage:
    cd backend
    python -m scripts.seed_loader --country ALL      # seed every country
    python -m scripts.seed_loader --country AE       # seed only AE rows
    python -m scripts.seed_loader --country SA       # seed only SA rows
    python -m scripts.seed_loader --country ALL --reset  # truncate first

Country scope aligns with Law 5 (country is the orthogonal scope axis).
Money values remain strings in the seed constants so they round-trip as
Decimal per Law 19.
"""
