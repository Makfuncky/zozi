def _utcnow() -> str:
    return datetime.utcnow().isoformat()


def _load_json(name: str) -> dict[str, Any]:
    """Load seed data from the canonical Python constants module.

    The legacy ``seed_data/<name>`` JSON files are mirrored from the same
    constants; if the constants module is unavailable we fall back to JSON
    for offline dev tools.
    """
    constant_name = _JSON_TO_CONSTANT.get(name)
    if constant_name:
        try:
            from infrastructure.database.seed import _seed_constants
            value = getattr(_seed_constants, constant_name, None)
            if value is not None:
                return value
        except ImportError:
            pass
    # Backward-compat fallback: read from the legacy JSON file.
    import json
    path = SEED_DIR / name
    if not path.exists():
        return {}
    with path.open("r", encoding="utf-8") as fh:
        return json.load(fh)


def _filter_by_country(rows: Iterable[dict[str, Any]], country: str) -> list[dict[str, Any]]:
    if country == "ALL":
        return list(rows)
    if country not in ALLOWED_COUNTRIES:
        raise ValueError(f"Unknown country {country!r}. Use one of {ALLOWED_COUNTRIES} or ALL.")
    return [r for r in rows if r.get("country_code") == country]


def _exec_many(cur: sqlite3.Cursor, sql: str, rows: list[tuple]) -> int:
    """Insert rows one at a time, skipping FK violations.

    Some pre-existing rows in the demo DB have stale supplier FKs (the original
    audit's data-integrity issue, not ours). INSERT OR IGNORE keeps the
    loader non-destructive: if the row already exists or the FK is bad, we
    move on rather than crashing the whole seed run.
    """
    if not rows:
        return 0
    # Convert to INSERT OR IGNORE
    ignored = sql.replace("INSERT OR REPLACE", "INSERT OR IGNORE", 1)
    n = 0
    for row in rows:
        try:
            cur.execute(ignored, row)
            n += 1
        except sqlite3.IntegrityError:
            # Skip row that fails FK check; pre-existing data
            continue
    return n


def seed_suppliers(cur: sqlite3.Cursor, country: str) -> int:
    data = _load_json("suppliers_full.json").get("suppliers", [])
    rows = _filter_by_country(data, country)
    now = _utcnow()
    out: list[tuple] = []
    for s in rows:
        out.append((
            s["uuid"],
            1,                                  # version
            0,                                  # is_deleted
            None,                               # deleted_at
            None,                               # deleted_by
            None,                               # created_by
            None,                               # updated_by
            s["id"],
            s["user_id"],
            s["business_name"],
            s["country_code"],
            s.get("address"),
            s.get("website"),
            s.get("bio"),
            s.get("business_type"),
            None,                               # verified_documents
            1 if s.get("is_verified") else 0,
            s.get("verification_status", "pending"),
            s.get("credibility_score", 0.0),
            now, now,
        ))
    sql = (
        "INSERT OR REPLACE INTO supplier_profiles "
        "(uuid, version, is_deleted, deleted_at, deleted_by, created_by, updated_by, "
        " id, user_id, business_name, country_code, address, website, bio, business_type, "
        " verified_documents, is_verified, verification_status, credibility_score, "
        " created_at, updated_at) VALUES "
        "(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)"
    )
    return _exec_many(cur, sql, out)


