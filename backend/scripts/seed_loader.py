def seed_country_staff_assignments(cur: sqlite3.Cursor, country: str) -> int:
    """Seed country_staff_assignments for demo admin/supplier/customer.

    Required so that ``auth.country_access_check()`` returns the right
    country for the demo users (Law 5: country is the orthogonal scope
    axis). Without these rows, the empty table causes RLS to grant
    access to every country, defeating country isolation.
    """
    cur.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='country_staff_assignments'")
    if cur.fetchone() is None:
        print("  country_staff_assignments: table missing, skipping")
        return 0

    data = _load_json("country_staff_assignments_full.json").get("country_staff_assignments", [])
    rows = _filter_by_country(data, country)
    if not rows:
        return 0

    email_to_id: dict[str, int] = {}
    cur.execute("SELECT id, email FROM users")
    for uid, email in cur.fetchall():
        if email:
            email_to_id[email] = uid

    now = _utcnow()
    out: list[tuple] = []
    for a in rows:
        uid = email_to_id.get(a["user_email"])
        if uid is None:
            continue
        out.append((
            a["id"],
            uid,
            a["country_code"],
            a.get("role_in_country", "country_manager"),
            1 if a.get("is_active", True) else 0,
            None,                               # assigned_by
            a.get("notes"),
            1,                                  # version (audit columns)
            now, now,
        ))
    sql = (
        "INSERT OR REPLACE INTO country_staff_assignments "
        "(id, user_id, country_code, role_in_country, is_active, assigned_by, "
        " notes, version, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?)"
    )
    return _exec_many(cur, sql, out)


