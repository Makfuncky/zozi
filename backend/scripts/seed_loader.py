def seed_all(country: str = "ALL", reset: bool = False, strict: bool = False) -> dict[str, int]:
    """Run every ``seed_*`` step and return a dict of {table: rows_written}."""
    if not DB_PATH.exists():
        raise FileNotFoundError(
            f"{DB_PATH} not found. Run the alembic migrations and create_demo_db first."
        )
    conn = sqlite3.connect(str(DB_PATH))
    conn.execute("PRAGMA foreign_keys = ON")
    cur = conn.cursor()
    if reset:
        for table in (
            "supplier_profiles", "customers", "logistics_partners",
            "products", "banners", "flash_discounts", "employees",
            "categories", "users", "country_staff_assignments",
        ):
            try:
                cur.execute(f"DELETE FROM {table}")
            except sqlite3.OperationalError:
                pass
        conn.commit()

    summary: dict[str, int] = {}
    steps = [
        ("categories", seed_categories),
        ("users", seed_users),
        ("suppliers", seed_suppliers),
        ("customers", seed_customers),
        ("logistics_partners", seed_logistics_partners),
        ("products", seed_products),
        ("banners", seed_banners),
        ("flash_discounts", seed_flash_discounts),
        ("employees", seed_employees),
        ("country_staff_assignments", seed_country_staff_assignments),
    ]
    for label, fn in steps:
        n = fn(cur, country)
        conn.commit()
        summary[label] = n
        if strict and n == 0:
            raise RuntimeError(
                f"STRICT: {label} produced 0 rows for country={country}; aborting"
            )
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description="Seed ZOZI demo data from JSON")
    parser.add_argument("--country", default="ALL", choices=("AE", "SA", "ALL"))
    parser.add_argument("--reset", action="store_true", help="truncate target tables first")
    parser.add_argument("--strict", action="store_true", help="abort on first step that produces 0 rows")
    args = parser.parse_args()

    summary = seed_all(args.country, reset=args.reset, strict=args.strict)
    for table, n in summary.items():
        print(f"  {table}: {n} rows")
    print(f"Done. country={args.country} reset={args.reset} strict={args.strict}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
