WEBHOOK_PATH_PREFIXES = (
    "/payments/webhook",
    "/payments/tap/webhook",
    "/email/webhooks",
)


def _extract_client_ip(request: Request) -> str | None:
    forwarded = request.headers.get("X-Forwarded-For", "")
    if forwarded:
        return forwarded.split(",")[0].strip()

    real_ip = request.headers.get("X-Real-IP", "")
    if real_ip:
        return real_ip.strip()

    if request.client:
        return request.client.host

    return None


def _is_ip_in_ranges(ip_str: str, ranges: list[str]) -> bool:
    try:
        ip = ipaddress.ip_address(ip_str)
    except ValueError:
        return False

    for cidr in ranges:
        try:
            network = ipaddress.ip_network(cidr, strict=False)
            if ip in network:
                return True
        except ValueError:
            continue

    return False


def _resolve_provider_from_path(path: str) -> str | None:
    if "/payments/webhook/" in path:
        parts = path.split("/")
        for i, part in enumerate(parts):
            if part == "webhook" and i + 1 < len(parts):
                provider = parts[i + 1]
                if provider in PROVIDER_IP_RANGES:
                    return provider
                return None
    if "/payments/tap/webhook" in path:
        return "tap" if "tap" in PROVIDER_IP_RANGES else None
    if "/email/webhooks" in path:
        return "resend" if "resend" in PROVIDER_IP_RANGES else None
    return None


class WebhookIPWhitelistMiddleware(BaseHTTPMiddleware):
    async def dispatch(self, request: Request, call_next) -> Response:
        if request.method == "OPTIONS":
            return await call_next(request)

        path = request.url.path

        if not path.startswith(WEBHOOK_PATH_PREFIXES):
            return await call_next(request)

        provider = _resolve_provider_from_path(path)
        if provider is None:
            return await call_next(request)

        ranges = PROVIDER_IP_RANGES.get(provider)
        if not ranges:
            return JSONResponse(
                status_code=404,
                content={"detail": "Not found"},
            )

        client_ip = _extract_client_ip(request)
        if client_ip is None or not _is_ip_in_ranges(client_ip, ranges):
            logger.warning(
                "Webhook blocked for provider=%s from IP=%s (not in whitelist)",
                provider,
                client_ip,
            )
            return JSONResponse(
                status_code=404,
                content={"detail": "Not found"},
            )

        return await call_next(request)

