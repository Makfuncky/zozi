API_VERSION_PREFIX = "/api/v1"

# ─────────────────────────────────────────────────────────────────────────────
# §2 — SURFACE CONFIGURATION
# ─────────────────────────────────────────────────────────────────────────────
# Surfaces map a path prefix to an auth dependency and the backing controller
# module. They are used to (a) pick the router prefix and (b) name the generated
# router file as ``{surface}_{feature}_{domain}.py``.
SURFACES: dict[str, dict[str, str]] = {
    "admin":     {"prefix": "/api/v1/admin",     "auth": "get_current_admin",    "mod": "controllers.security.auth_controller"},
    "customer":  {"prefix": "/api/v1/customer",  "auth": "get_current_user",     "mod": "controllers.security.auth_controller"},
    "supplier":  {"prefix": "/api/v1/supplier",  "auth": "get_current_user",     "mod": "controllers.security.auth_controller"},
    "logistics": {"prefix": "/api/v1/logistics", "auth": "get_current_user",     "mod": "controllers.security.auth_controller"},
    "public":    {"prefix": "/api/v1",           "auth": "get_optional_user",    "mod": "controllers.security.auth_controller"},
    "system":    {"prefix": "/api/v1/system",    "auth": "get_current_admin",    "mod": "controllers.security.auth_controller"},
    "internal":  {"prefix": "/api/v1/internal",  "auth": "get_current_admin",    "mod": "controllers.security.auth_controller"},
}


def _surface_for_path(path: str):
    """Return (surface_name, prefix) for the longest SURFACES prefix that is a
    prefix of ``path``, else (None, None)."""
    best = None
    for name, cfg in SURFACES.items():
        p = cfg["prefix"]
        if path.startswith(p) and (best is None or len(p) > len(best[1])):
            best = (name, p)
    return best


def _derive_filename(module: str, routes: "list") -> str:
    """``{surface}_{feature}_{domain}.py`` for a controller module.

    surface  — derived from the route path via SURFACES
    feature  — second-to-last module segment (the subpackage, e.g. 'commerce')
    domain   — last segment minus a trailing '_controller'
    """
    active = [m for m in routes if not m["skip"] and m["method"] != "WEBSOCKET"]
    _surf = _surface_for_path(active[0]["path"]) if active else None
    surface = _surf[0] if _surf else "public"
    parts = [p for p in module.split(".") if p not in ("controllers", "__init__")]
    domain = parts[-1]
    if domain.endswith("_controller"):
        domain = domain[: -len("_controller")]
    feature = parts[-2] if len(parts) >= 2 else ""
    base = "_".join(x for x in (surface, feature, domain) if x)
    return base + ".py"


# Identifiers that must NOT be re-imported from the controller module (they live
# in stdlib / FastAPI / SQLAlchemy, or are emitted by the generator itself).
_BUILTIN_NAMES = {
    "int", "str", "bool", "float", "bytes", "complex", "object", "type",
    "dict", "list", "set", "tuple", "frozenset", "None", "True", "False",
    "Any", "Optional", "List", "Dict", "Decimal", "Session", "Request",
    "BackgroundTasks", "APIRouter", "Depends", "Body", "Query",
}
PATH_RE = re.compile(r"{([^}]+)}")
FORBIDDEN = ("db.commit", "session.commit", "db.flush", "session.flush",
             "from models import", "from services import", "from data.models import")

KNOWN_DEPS = {
    "db": ("db", "Session", "Depends(get_db)"),
    "admin": ("current_user", "dict", "Depends(require_admin)"),
    "user": ("current_user", "dict", "Depends(get_current_user)"),
    "optional_user": ("current_user", "Optional[dict]", "Depends(get_current_user_optional)"),
    "background_tasks": ("background_tasks", "BackgroundTasks", None),
    "request": ("request", "Request", None),
}

HTTP_METHODS = {"GET", "POST", "PUT", "PATCH", "DELETE"}


# ─────────────────────────────────────────────────────────────────────────────
# Route-contract decorators (CONTROLLERS layer, metadata only — no FastAPI here)
# ─────────────────────────────────────────────────────────────────────────────
def route(
    method: str,
    path: str,
    *,
    deps: "Optional[list]" = None,
    query: "Optional[list]" = None,
    body=None,
    response_model=None,
    status_code: int = 200,
    tags: "Optional[list]" = None,
    rls: "Optional[str]" = None,
    skip: bool = False,
    **kwargs,
) -> "Any":
    """Declare the HTTP contract for a controller function. No FastAPI here."""
    def decorator(func):
        func._route_meta = {
            "method": method.upper(),
            "path": path,
            "deps": list(deps or []),
            "query": list(query or []),
            "body": body,
            "response_model": response_model,
            "status_code": status_code,
            "tags": list(tags or []),
            "rls": rls,
            "skip": bool(skip),
            **kwargs,
        }
        return func
    return decorator


def get(path: str, **kw):
    return route("GET", path, **kw)


def post(path: str, **kw):
    kw.setdefault("status_code", 201)
    return route("POST", path, **kw)


def put(path: str, **kw):
    return route("PUT", path, **kw)


def patch(path: str, **kw):
    return route("PATCH", path, **kw)


def delete(path: str, **kw):
    return route("DELETE", path, **kw)


# ─────────────────────────────────────────────────────────────────────────────
# AST helpers
# ─────────────────────────────────────────────────────────────────────────────
def _unparse(node: ast.AST) -> str:
    if astunparse is not None:
        try:
            return astunparse.unparse(node).strip()
        except Exception:
            pass
    return ast.unparse(node).strip()


def _const_list(value: ast.AST) -> "list":
    if isinstance(value, ast.List):
        return [str(el.value) for el in value.elts if isinstance(el, ast.Constant)]
    return []


def _const_str(value: ast.AST) -> "Optional[str]":
    if isinstance(value, ast.Constant) and isinstance(value.value, str):
        return value.value
    return None


def _const_int(value: ast.AST) -> "Optional[int]":
    if isinstance(value, ast.Constant) and isinstance(value.value, int):
        return int(value.value)
    return None


def _const_bool(value: ast.AST) -> bool:
    if isinstance(value, ast.Constant) and isinstance(value.value, bool):
        return bool(value.value)
    return False


def parse_decorator(dec: ast.AST) -> "Optional[dict]":
    if not isinstance(dec, ast.Call):
        return None
    f = dec.func
    if not isinstance(f, ast.Name):
        return None
    name = f.id
    args = dec.args
    kwargs = {kw.arg: kw.value for kw in dec.keywords if kw.arg}
    if name in ("get", "post", "put", "patch", "delete"):
        method = name.upper()
        path = _const_str(args[0]) if args else None
    elif name == "route":
        method = _const_str(args[0]) if len(args) >= 1 else _const_str(kwargs.get("method"))
        path = _const_str(args[1]) if len(args) >= 2 else _const_str(kwargs.get("path"))
    else:
        return None
    if not method or not path:
        return None
    status = _const_int(kwargs.get("status_code"))
    if status is None:
        status = 201 if method == "POST" else 200
    extra = {}
    for k in EXTRA_FORWARD_KEYS:
        if k in kwargs and kwargs[k] is not None:
            node = kwargs[k]
            if isinstance(node, ast.Constant):
                extra[k] = node.value
            else:
                extra[k] = _unparse(node)
    return {
        "method": method.upper(),
        "path": path,
        "deps": _const_list(kwargs.get("deps", ast.List(elts=[]))),
        "query": _const_list(kwargs.get("query", ast.List(elts=[]))),
        "body": kwargs.get("body"),
        "response_model": kwargs.get("response_model"),
        "status_code": status,
        "tags": _const_list(kwargs.get("tags", ast.List(elts=[]))),
        "rls": _const_str(kwargs.get("rls")) if kwargs.get("rls") else None,
        "skip": _const_bool(kwargs.get("skip")) if kwargs.get("skip") else False,
        "extra": extra,
    }


def annotation_of(arg: ast.arg) -> "Optional[str]":
    if arg.annotation is not None:
        return _unparse(arg.annotation)
    return None


def _collect_type_names(target: "Any", sink: "set") -> None:
    """Pull every identifier token out of an annotation / type expression so the
    generated router can re-import it from the controller module."""
    if target is None:
        return
    text = _unparse(target) if isinstance(target, ast.AST) else str(target)
    for tok in re.findall(r"[A-Za-z_][A-Za-z0-9_]*", text):
        sink.add(tok)


# Decorator kwargs that should be forwarded onto the generated FastAPI route.
EXTRA_FORWARD_KEYS = ("summary", "description", "deprecated", "responses")


def _default_src(default_node: "Optional[ast.AST]") -> "Optional[str]":
    """Source text of a parameter's default expression, or None if required."""
    if default_node is None:
        return None
    return _unparse(default_node)


def _order_params(roles: "list") -> "list":
    """FastAPI/Python require non-default params before defaulted ones.

    Path params carry no default, so they must lead the signature. ``**rest``
    must always be last.
    """
    path = [p for p in roles if p["role"] == "path"]
    rest = [p for p in roles if p["role"] == "rest"]
    others = [p for p in roles if p["role"] not in ("path", "rest")]
    return path + others + rest


def _existing_routes(out_dir: str) -> "set":
    """Collect ``(METHOD, full_path)`` already published by committed routers in
    ``out_dir`` (hand-written AND previously-generated) so the generator can
    avoid registering the same path twice."""
    known = set()
    if not os.path.isdir(out_dir):
        return known
    for fn in os.listdir(out_dir):
        if not fn.endswith(".py") or fn == "__init__.py":
            continue
        fp = os.path.join(out_dir, fn)
        try:
            text = open(fp, encoding="utf-8").read()
        except Exception:
            continue
        # Our own generated artifacts (they carry the AUTO-GENERATED marker)
        # will be (re)written by this run, so they must NOT count as collisions
        # — only hand-written / legacy routers do.
        if MARKER in text:
            continue
        prefix = ""
        m = re.search(r'APIRouter\(\s*prefix\s*=\s*"([^"]*)"', text)
        if m:
            prefix = m.group(1)
        for mm in re.finditer(r'@\w+\.(get|post|put|patch|delete)\(\s*"([^"]*)"', text):
            method = mm.group(1).upper()
            path = mm.group(2)
            full = prefix + path if path.startswith("/") else prefix + "/" + path
            known.add((method, full))
    return known


def scan_controllers() -> "list":
    """Return list of controller modules with their declared routes."""
    modules = []
    for dirpath, _, files in os.walk(CONTROLLERS_DIR):
        for fn in sorted(files):
            if not fn.endswith(".py") or fn == "__init__.py":
                continue
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, ROOT)
            mod_path = rel[:-3].replace(os.sep, ".")
            try:
                tree = ast.parse(open(full, encoding="utf-8").read(), filename=full)
            except SyntaxError as e:
                print(f"WARN: syntax error in {rel}: {e}", file=sys.stderr)
                continue
            routes = []
            for node in ast.walk(tree):
                if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    continue
                # Positional args carry defaults in ``node.args.defaults``,
                # aligned to the TAIL of the arg list (not per-arg).
                pos_args = node.args.args
                pos_defaults = node.args.defaults
                n_pos = len(pos_args)
                n_def = len(pos_defaults)
                default_src = [None] * (n_pos - n_def) + [_default_src(d) for d in pos_defaults]
                param_list = [
                    {"name": a.arg, "ann": annotation_of(a),
                     "default": default_src[i]}
                    for i, a in enumerate(pos_args)
                ]
                # Keyword-only args (e.g. cursor: Optional[int] = None). Their
                # defaults live in ``node.args.kw_defaults`` (aligned to the tail
                # of ``kwonlyargs``), NOT on the arg node itself.
                kw_defaults = node.args.kw_defaults
                for k, a in enumerate(node.args.kwonlyargs):
                    dflt = kw_defaults[k] if k < len(kw_defaults) else None
                    param_list.append(
                        {"name": a.arg, "ann": annotation_of(a),
                         "default": _default_src(dflt)})
                # ``**rest`` passthrough (e.g. **kwargs) so generation never
                # crashes on catch-all signatures.
                if node.args.kwarg is not None:
                    param_list.append(
                        {"name": node.args.kwarg.arg,
                         "ann": annotation_of(node.args.kwarg), "rest": True})
                # Collect EVERY route decorator on the function. A single handler
                # may serve multiple paths (e.g. admin + public prefixes), each
                # declared with its own stacked decorator.
                for dec in node.decorator_list:
                    meta = parse_decorator(dec)
                    if not meta:
                        continue
                    meta["func"] = node.name
                    meta["is_async"] = isinstance(node, ast.AsyncFunctionDef)
                    meta["params"] = param_list
                    meta["returns"] = _unparse(node.returns) if node.returns else None
                    routes.append(meta)
            if routes:
                modules.append({"module": mod_path, "file": rel, "routes": routes})
    return modules


def assign_roles(meta: dict, module: str) -> "list":
    """Decide each parameter's role for the generated wrapper."""
    path_names = set(PATH_RE.findall(meta["path"]))
    deps = set(meta["deps"])
    query = set(meta["query"])
    dep_param_to_key = {}
    for d in deps:
        pname = KNOWN_DEPS.get(d, (d, None, None))[0]
        dep_param_to_key[pname] = d
    out = []
    leftovers = []
    for p in meta["params"]:
        n = p["name"]
        if p.get("rest"):
            out.append({"name": n, "ann": p["ann"] or "dict", "role": "rest"})
            continue
        if n in path_names:
            out.append({"name": n, "ann": p["ann"] or "str", "role": "path", "default": p.get("default")})
        elif n in dep_param_to_key:
            out.append({"name": n, "ann": p["ann"], "role": "dep", "dep": dep_param_to_key[n], "default": p.get("default")})
        elif n in query:
            out.append({"name": n, "ann": p["ann"] or "str", "role": "query", "default": p.get("default")})
        else:
            leftovers.append({"name": n, "ann": p["ann"], "role": "unknown", "default": p.get("default")})
    if meta["body"] is not None:
        if len(leftovers) != 1:
            raise ValueError(
                f"{module}.{meta['func']}: 'body' set but found "
                f"{len(leftovers)} non-path/non-dep args (expected 1)"
            )
        leftovers[0]["role"] = "body"
        out.append(leftovers[0])
    else:
        for lo in leftovers:
            if meta["method"] in ("POST", "PUT", "PATCH"):
                lo["role"] = "bodyfield"
            else:
                lo["role"] = "query"
            out.append(lo)
    return out


def emit_param(p: dict, method: str) -> str:
    name = p["name"]
    ann = p.get("ann") or "str"
    role = p["role"]
    default = p.get("default")
    if role == "path":
        return f"{name}: {ann}"
    if role == "dep":
        dep = p["dep"]
        pname, ptype, wiring = KNOWN_DEPS.get(dep, (name, ann, None))
        if wiring is None:
            return f"{pname}: {ptype}"
        return f"{pname}: {ptype} = {wiring}"
    if role == "query":
        if default is not None:
            return f"{name}: {ann} = Query({default})"
        return f"{name}: {ann} = Query(None)"
    if role == "body":
        if default is not None:
            return f"{name}: {ann} = Body({default})"
        return f"{name}: {ann} = Body(...)"
    if role == "bodyfield":
        if default is not None:
            return f"{name}: {ann} = Body({default})"
        return f"{name}: {ann} = Body(...)"
    if role == "rest":
        return f"**{name}"
    return f"{name}: {ann}"


def generate_router_file(module_info: dict, collisions: "Optional[set]" = None,
                           skipped: "Optional[list]" = None) -> str:
    mod = module_info["module"]
    collisions = collisions or set()
    needs_body = False
    needs_query = False
    fastapi_extras = set()
    dep_imports = set()
    ann_imports = set()
    # Identifiers (Pydantic schemas, ORM models, enums, ...) referenced by route
    # annotations / response_model / body that must be re-imported from the
    # controller module so the generated file is self-contained.
    type_names = set()
    route_funcs = []
    func_imports = set()

    active = [m for m in module_info["routes"]
              if not m["skip"] and m["method"] != "WEBSOCKET"]
    # Pick a router prefix from the surface that all active routes share. This
    # yields e.g. ``/api/v1/admin`` for admin controllers (instead of a bare
    # ``/api/v1``), so the surface is reflected in the mounted routes. Falls
    # back to a shared ``/api/v1`` prefix, then to no prefix.
    surf = {_surface_for_path(m["path"]) for m in active
            if _surface_for_path(m["path"])[0]}
    if len(surf) == 1:
        router_prefix = next(iter(surf))[1]
    elif all(m["path"].startswith(API_VERSION_PREFIX) for m in active):
        router_prefix = API_VERSION_PREFIX
    else:
        router_prefix = ""

    for meta in active:
        roles = assign_roles(meta, module_info["module"])
        route_path = meta["path"]
        decorator_path = route_path
        if router_prefix and route_path.startswith(router_prefix):
            decorator_path = route_path[len(router_prefix):]
            if not decorator_path:
                decorator_path = ""
        full = (router_prefix + decorator_path) or "/"
        if (meta["method"], full) in collisions:
            if skipped is not None:
                skipped.append((meta["method"], full, meta["func"]))
            continue
        deco = f"@router.{meta['method'].lower()}(\"{decorator_path}\""
        extras = []
        if meta.get("response_model") is not None:
            extras.append(f"response_model={_unparse(meta['response_model'])}")
            _collect_type_names(meta["response_model"], type_names)
        if meta.get("status_code"):
            extras.append(f"status_code={meta['status_code']}")
        if meta.get("tags"):
            tags = ", ".join(repr(t) for t in meta["tags"])
            extras.append(f"tags=[{tags}]")
        extra = meta.get("extra") or {}
        for k in ("summary", "description"):
            if extra.get(k):
                extras.append(f"{k}={json.dumps(extra[k])}")
        if extra.get("deprecated"):
            extras.append("deprecated=True")
        if extra.get("responses") is not None:
            extras.append(f"responses={_unparse(extra['responses'])}")
        if extras:
            deco += ", " + ", ".join(extras)
        deco += ")"

        if meta.get("body") is not None:
            _collect_type_names(meta["body"], type_names)

        for p in roles:
            if p["role"] in ("bodyfield", "body"):
                needs_body = True
            if p["role"] == "query":
                needs_query = True
            if p["role"] == "dep":
                dep = p["dep"]
                pname, ptype, wiring = KNOWN_DEPS.get(dep, (p["name"], p.get("ann") or "str", None))
                _collect_type_names(ptype, ann_imports)
                if dep == "db":
                    dep_imports.add("from db.database import get_db")
                elif dep == "admin":
                    dep_imports.add("from utils.dependencies import require_admin")
                elif dep == "user":
                    dep_imports.add("from utils.dependencies import get_current_user")
                elif dep == "optional_user":
                    dep_imports.add("from utils.dependencies import get_current_user_optional")
                elif dep == "background_tasks":
                    fastapi_extras.add("BackgroundTasks")
                elif dep == "request":
                    fastapi_extras.add("Request")
            if p.get("ann"):
                _collect_type_names(p["ann"], ann_imports)
        if meta.get("returns"):
            _collect_type_names(meta["returns"], ann_imports)
        params_str = ",\n    ".join(emit_param(p, meta["method"]) for p in _order_params(roles))
        ret = f" -> {meta['returns']}" if meta.get("returns") else ""
        func_imports.add(meta["func"])
        prefix = "async def" if meta.get("is_async") else "def"
        call_parts = []
        for p in roles:
            if p["role"] == "rest":
                call_parts.append(f"**{p['name']}")
            else:
                call_parts.append(f"{p['name']}={p['name']}")
        call = f"{meta['func']}({', '.join(call_parts)})"
        ret_stmt = f"    return await {call}" if meta.get("is_async") else f"    return {call}"
        body_lines = [f"{deco}", f"{prefix} {meta['func']}_route(", f"    {params_str}", f"){ret}:"]
        body_lines.append(ret_stmt)
        route_funcs.append("\n".join(body_lines))

    # Nothing to emit: every discovered route collided with an existing
    # (hand-written) router, so this controller is already fully served.
    # Returning "" signals callers to skip writing / skip verification.
    if not route_funcs:
        return ""

    lines = [f'"""{MARKER}"""', "from __future__ import annotations", ""]
    fastapi_parts = ["APIRouter", "Depends"]
    if needs_body:
        fastapi_parts.append("Body")
    if needs_query:
        fastapi_parts.append("Query")
    fastapi_parts.extend(sorted(fastapi_extras))
    lines.append("from fastapi import " + ", ".join(fastapi_parts))
    lines.append("from sqlalchemy.orm import Session")
    for d in sorted(dep_imports):
        lines.append(d)
    if "Decimal" in ann_imports or "Decimal" in type_names:
        lines.append("from decimal import Decimal")
    typing_imports = [t for t in ("Any", "Optional", "List", "Dict") if t in ann_imports or t in type_names]
    if typing_imports:
        lines.append("from typing import " + ", ".join(sorted(set(typing_imports))))
    lines.append("")
    # Re-export every referenced symbol (controller funcs + type hints) from the
    # controller module in a single import so the generated router is self-contained.
    controller_symbols = sorted(set(func_imports) | (type_names - _BUILTIN_NAMES))
    lines.append(f"from {mod} import {', '.join(controller_symbols)}")
    lines.append("")
    if router_prefix:
        lines.append(f"router = APIRouter(prefix=\"{router_prefix}\")")
    else:
        lines.append("router = APIRouter()")
    lines.append("")
    lines.append("\n\n".join(route_funcs))
    lines.append("")
    return "\n".join(lines)


def validate(modules: "list") -> "list":
    errors = []
    seen = {}
    for mi in modules:
        for meta in mi["routes"]:
            if meta["skip"]:
                continue
            key = (meta["method"], meta["path"])
            if key in seen:
                errors.append(
                    f"DUPLICATE route {meta['method']} {meta['path']} "
                    f"in {mi['module']} ({meta['func']}) and {seen[key]}")
            else:
                seen[key] = f"{mi['module']}.{meta['func']}"
    return errors


def check_forbidden(text: str, label: str) -> "list":
    """Reject generated routers that violate the architecture contract."""
    problems = []
    for pat in FORBIDDEN:
        if pat in text:
            problems.append(f"FORBIDDEN pattern {pat!r} in {label}")
    return problems


def validate_existing_routers(out_dir: str) -> "list":
    """Scan already-committed routers for forbidden patterns (legacy --validate)."""
    problems = []
    if not os.path.isdir(out_dir):
        return problems
    for fn in sorted(os.listdir(out_dir)):
        if not fn.endswith(".py") or fn == "__init__.py":
            continue
        fp = os.path.join(out_dir, fn)
        try:
            text = open(fp, encoding="utf-8").read()
        except Exception:
            continue
        for pat in FORBIDDEN:
            if pat in text:
                problems.append(f"FORBIDDEN pattern {pat!r} in {fn}")
        try:
            tree = ast.parse(text)
            for node in ast.walk(tree):
                if isinstance(node, ast.ImportFrom) and node.module is not None:
                    if node.module.startswith("models") and "db" not in node.module:
                        problems.append(f"imports models ({node.module}) in {fn}")
                    if node.module.startswith("services"):
                        problems.append(f"imports services ({node.module}) in {fn}")
        except SyntaxError:
            problems.append(f"syntax error in {fn}")
    return problems


def _run_verify(modules: "list", out_dir: str, collisions: "Optional[set]" = None) -> int:
    """Compare freshly generated artifacts against what is committed on disk.

    Returns 1 (and lists errors) if any generated file is missing, drifted, or
    orphaned — this is the CI gate that forces ``auto_router.py`` to be re-run
    after controller changes.
    """
    errors = validate(modules)
    # Protect the bootability contract: the crash-proof loader in main.py must
    # survive any router regeneration, so CI fails if it has been clobbered.
    errors.extend(_loader_is_crashproof())
    if collisions is None:
        collisions = _existing_routes(out_dir)

    generated = {}
    for mi in modules:
        if not mi["routes"]:
            continue
        fname = _derive_filename(mi["module"], mi["routes"])
        generated[fname] = generate_router_file(mi, collisions=collisions)

    os.makedirs(out_dir, exist_ok=True)
    for fname, content in generated.items():
        if not content:
            continue
        target = os.path.join(out_dir, fname)
        if not os.path.exists(target):
            errors.append(
                f"MISSING generated file: {target} — run `python routers/generated/auto_router.py`")
            continue
        existing = open(target, encoding="utf-8").read()
        if existing != content:
            errors.append(
                f"DRIFT: {target} is out of sync with controllers — "
                f"run `python routers/generated/auto_router.py`")

    # orphan generated files: carry the marker but have no decorated controller
    if os.path.isdir(out_dir):
        for fn in os.listdir(out_dir):
            if not fn.endswith(".py") or fn in ("__init__.py",):
                continue
            fp = os.path.join(out_dir, fn)
            try:
                head = open(fp, encoding="utf-8").read(400)
            except Exception:
                continue
            if MARKER not in head:
                continue
            if fn not in generated:
                errors.append(
                    f"ORPHAN: {fp} has no decorated controller — "
                    f"run `python routers/generated/auto_router.py --clean`")

    total = sum(len(m["routes"]) for m in modules)
    print(f"VERIFY: {len(modules)} modules, {total} routes -> {out_dir}")
    if errors:
        for e in errors:
            print("  ERROR:", e, file=sys.stderr)
        return 1
    print("  OK — generated files are in sync with controllers")
    return 0


def _read_head(target: str, n: int = 400) -> str:
    try:
        return open(target, encoding="utf-8").read(n)
    except Exception:
        return ""


# ─────────────────────────────────────────────────────────────────────────────
# §3 — LOADER CONTRACT GUARD
# ─────────────────────────────────────────────────────────────────────────────
# This generator ONLY writes thin router files into the ``routers/`` SURFACE
# folder. It must NEVER touch ``main.py`` — the crash-proof discovery loader in
# ``main._load_routers()`` is hand-maintained and is what keeps the app bootable
# when a router file is broken. If that loader is ever rewritten to hard-crash on
# a missing prefix or a bad import, startup breaks again. ``_loader_is_crashproof``
# asserts the guard is present so ``--verify`` (CI) refuses to bless a regen that
# shipped alongside a clobbered loader.
_LOADER_GUARDS = {
    "_load_routers defined": "def _load_routers",
    "per-router import is tolerated": "failed_routers.append",
    "None-safe prefix read": 'getattr(_module, "__router_prefix__", None)',
    "include errors are tolerated": 'logger.error("Skipping router',
}


def _loader_is_crashproof() -> "list":
    """Return problems if ``main.py`` does NOT contain the crash-proof loader."""
    problems = []
    main_py = os.path.join(ROOT, "main.py")
    if not os.path.isfile(main_py):
        return problems  # nothing to guard against
    text = open(main_py, encoding="utf-8").read()
    for label, needle in _LOADER_GUARDS.items():
        if needle not in text:
            problems.append(f"main.py loader missing crash-proof guard: {label}")
    return problems


def _guard_target(target: str) -> "Optional[str]":
    """Return a refusal reason if ``target`` is a path this generator must never
    write (notably ``main.py``), else None."""
    if os.path.basename(target) == "main.py":
        return "REFUSE to write main.py (crash-proof loader is hand-maintained)"
    return None


def _backup_if_exists(target: str) -> None:
    if os.path.exists(target):
        shutil.copy2(target, target + ".bak")


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
        sys.stderr.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
    except Exception:
        pass
    ap = argparse.ArgumentParser(description="ZOZI Auto-Router (single file)")
    ap.add_argument("--out", default=DEFAULT_OUT, help="output directory (default: routers/ surface)")
    ap.add_argument("--dry-run", action="store_true", help="print to stdout only")
    ap.add_argument("--check", action="store_true", help="validate + summary, exit 1 on fail")
    ap.add_argument("--verify", action="store_true", help="ensure committed generated files match controllers")
    ap.add_argument("--report", action="store_true", help="print discovered routes")
    ap.add_argument("--clean", action="store_true", help="remove orphan generated files")
    ap.add_argument("--validate", action="store_true", help="check existing routers for forbidden patterns")
    ap.add_argument("--backup", action="store_true", help="back up before overwrite")
    ap.add_argument("--force", action="store_true",
                    help="allow routes that collide with existing routers (no skip)")
    ap.add_argument("--domain", default=None, help="filter module by substring")
    args = ap.parse_args()

    modules = scan_controllers()
    if args.domain:
        modules = [m for m in modules if args.domain in m["module"]]

    if args.report:
        for m in modules:
            for r in m["routes"]:
                flag = " (skip)" if r["skip"] else ""
                print(f"{r['method']:7} {r['path']:45} {m['module']}.{r['func']}{flag}")
        print(f"\n{len(modules)} controller modules, "
              f"{sum(len(m['routes']) for m in modules)} decorated functions")
        return 0

    if args.validate:
        problems = validate_existing_routers(args.out)
        if problems:
            for p in problems:
                print("  ERROR:", p, file=sys.stderr)
            print(f"\nVALIDATE: {len(problems)} issue(s) found")
            return 1
        print(f"VALIDATE: OK — no forbidden patterns in {args.out}")
        return 0

    errors = validate(modules)

    if args.check:
        total = sum(len(m["routes"]) for m in modules)
        print(f"CHECK: {len(modules)} modules, {total} routes")
        for mi in modules:
            errors.extend(check_forbidden(generate_router_file(mi), mi["module"]))
        if errors:
            for e in errors:
                print("  ERROR:", e, file=sys.stderr)
            return 1
        print("  OK — no duplicate routes, no forbidden patterns")
        return 0

    if args.verify:
        collisions = set() if args.force else _existing_routes(args.out)
        return _run_verify(modules, args.out, collisions=collisions)

    if args.clean:
        removed = 0
        if os.path.isdir(args.out):
            for fn in os.listdir(args.out):
                if not fn.endswith(".py") or fn == "__init__.py":
                    continue
                fp = os.path.join(args.out, fn)
                try:
                    head = open(fp, encoding="utf-8").read(400)
                except Exception:
                    continue
                if MARKER in head:
                    os.remove(fp)
                    removed += 1
        print(f"CLEAN: removed {removed} generated router file(s) from {args.out}")
        return 0

    # write / dry-run
    written = 0
    failed = 0
    skipped_routes = 0
    collisions = set() if args.force else _existing_routes(args.out)
    for mi in modules:
        skipped = []
        gen = generate_router_file(mi, collisions=collisions, skipped=skipped)
        if not gen:
            skipped_routes += len(skipped)
            continue
        fname = _derive_filename(mi["module"], mi["routes"])
        forb = check_forbidden(gen, mi["module"])
        if forb:
            failed += 1
            for f in forb:
                print("  ERROR:", f, file=sys.stderr)
            if not args.dry_run:
                continue
        skipped_routes += len(skipped)
        if args.dry_run:
            print(f"# ===== {fname} (from {mi['module']}) =====")
            print(gen)
            print()
            written += 1
        else:
            os.makedirs(args.out, exist_ok=True)
            target = os.path.join(args.out, fname)
            # Never write a file this generator must not own (e.g. main.py).
            refuse = _guard_target(target)
            if refuse:
                print(f"  {refuse}: {target}", file=sys.stderr)
                continue
            # Never overwrite a hand-written (non-marker) router.
            if os.path.exists(target) and MARKER not in _read_head(target):
                print(f"  SKIP (hand-written, not overwritten): {target}", file=sys.stderr)
                continue
            if args.backup:
                _backup_if_exists(target)
            with open(target, "w", encoding="utf-8") as fh:
                fh.write(gen)
            written += 1

    if skipped_routes:
        print(f"SKIPPED: {skipped_routes} route(s) colliding with existing routers "
              f"(use --force to emit them anyway)")
    if args.dry_run:
        print(f"DRY-RUN: would write {written} file(s) to {args.out}")
    else:
        print(f"WROTE: {written} file(s) to {args.out}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
