"""ZOZI Auto-Router — single source of truth (merges route.py + gen_routers.py
+ _registry.py + auto_router_gen.py into ONE file).

What this file does
───────────────────
1. Exposes the ONLY route-contract decorators controllers may import
   (``route`` / ``get`` / ``post`` / ``put`` / ``patch`` / ``delete``). They are
   metadata-only — a controller never imports FastAPI.
2. Reads those declarations from ``controllers/`` via **AST only** (it never
   imports or executes a controller, so a broken controller import cannot crash
   the scan).
3. Emits thin FastAPI routers that delegate to the controller functions, and
   writes them into the **surface folder** (``routers/`` by default) next to the
   hand-written routers.

Registration
────────────
Because the generated routers are written into ``routers/`` (the surface), the
existing auto-discovery in ``main._load_routers()`` (which globs ``routers/*.py``)
picks them up automatically — no central registry is needed. This replaces the
old ``routers/generated/_registry.py`` + ``register_all_routers()`` dance, which
double-registered and is now gone.

Usage
─────
    python routers/generated/auto_router.py                  # write routers/ (surface)
    python routers/generated/auto_router.py --out _preview   # write elsewhere (safe)
    python routers/generated/auto_router.py --dry-run        # print to stdout, write nothing
    python routers/generated/auto_router.py --check          # validate + summary, exit 1 on fail
    python routers/generated/auto_router.py --verify         # ensure committed files match controllers
    python routers/generated/auto_router.py --report         # print discovered routes
    python routers/generated/auto_router.py --validate       # check existing routers for forbidden patterns
    python routers/generated/auto_router.py --clean          # remove orphan generated files
    python routers/generated/auto_router.py --domain coupons # one module substring
    python routers/generated/auto_router.py --backup         # back up before overwrite

Generated files carry the AUTO-GENERATED marker and are never created over a
hand-written router (a file without the marker is left untouched).

Contract (controller function arguments):
    * arg named in the path {name}        -> path param
    * arg named in deps                   -> injected dependency
    * arg named in query                  -> query param
    * remaining arg when ``body`` set     -> the body model
    * remaining args otherwise            -> body fields (write) / query (read)
"""
