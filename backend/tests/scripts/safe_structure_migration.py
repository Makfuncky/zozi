@dataclass
class Action:
    kind: str
    src: str
    dst: str = ""
    reason: str = ""
    tracked: bool = False
    ignored: bool = False
    conflict: bool = False
    replacements: list = field(default_factory=list)
    create_init: bool = False
    reexport_module: str = ""
    status: str = "planned"
    error: str = ""


# ============================================================================
# HELPERS
# ============================================================================

def now_stamp() -> str:
    return datetime.datetime.now().strftime("%Y%m%d_%H%M%S")


def is_subpath(path: Path, base: Path) -> bool:
    try:
        path.relative_to(base)
        return True
    except ValueError:
        return False


def is_secret_file(rel_path: str) -> bool:
    p = rel_path.replace("\\", "/")
    return any(rx.search(p) for rx in SECRET_FILE_PATTERNS)


def classify_domain(stem: str) -> str:
    low = stem.lower()
    for domain, keywords in DOMAIN_KEYWORDS:
        for kw in keywords:
            if kw in low:
                return domain
    return "core"


def router_surface(stem: str) -> str:
    low = stem.lower()
    for surface in ["admin", "supplier", "customer", "public", "webhook"]:
        if low == surface or low.startswith(surface + "_"):
            return surface
    return "common"


def module_from_backend_path(rel_path: str) -> str:
    p = rel_path.replace("\\", "/")
    if not p.startswith("backend/"):
        return ""
    p = p[len("backend/"):]
    if p.endswith(".py"):
        p = p[:-3]
    if p.endswith("/__init__"):
        p = p[:-len("/__init__")]
    return p.replace("/", ".")


