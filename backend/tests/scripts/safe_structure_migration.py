class Migrator:
    def __init__(self, args: argparse.Namespace):
        self.args = args
        self.repo = Path(args.root).resolve()
        self.stamp = now_stamp()
        self.report_dir = self.repo / "migration_reports"
        self.backup_root = self.repo / ".migration_backups" / self.stamp
        self.actions: list[Action] = []
        self.replacements: list[tuple[str, str]] = []
        self.tracked_cache: dict[str, bool] = {}
        self.ignored_cache: dict[str, bool] = {}
        self.git_ok = self._is_git_repo()
        self.notes: list[str] = []

        if not self.repo.is_dir():
            print(f"[FATAL] Repo root not found: {self.repo}", file=sys.stderr)
            sys.exit(2)

        self.report_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # git
    # ------------------------------------------------------------------

    def _is_git_repo(self) -> bool:
        try:
            r = subprocess.run(
                ["git", "rev-parse", "--is-inside-work-tree"],
                cwd=self.repo,
                capture_output=True,
                text=True,
            )
            return r.returncode == 0 and r.stdout.strip() == "true"
        except Exception:
            return False

    def git(self, cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
        full = ["git"] + cmd
        r = subprocess.run(full, cwd=self.repo, capture_output=True, text=True)
        if check and r.returncode != 0:
            raise RuntimeError(f"Git command failed: {' '.join(full)}\n{r.stderr}")
        return r

    def is_tracked(self, rel_path: str) -> bool:
        rel_path = rel_path.replace("\\", "/")
        if rel_path in self.tracked_cache:
            return self.tracked_cache[rel_path]

        if not self.git_ok:
            self.tracked_cache[rel_path] = False
            return False

        r = self.git(["ls-files", "--error-unmatch", "--", rel_path], check=False)
        tracked = r.returncode == 0
        self.tracked_cache[rel_path] = tracked
        return tracked

    def is_ignored(self, rel_path: str) -> bool:
        rel_path = rel_path.replace("\\", "/")
        if rel_path in self.ignored_cache:
            return self.ignored_cache[rel_path]

        if not self.git_ok:
            self.ignored_cache[rel_path] = False
            return False

        r = self.git(["check-ignore", "-q", "--", rel_path], check=False)
        ignored = r.returncode == 0
        self.ignored_cache[rel_path] = ignored
        return ignored

    def git_status_dirty(self) -> bool:
        if not self.git_ok:
            return False
        r = self.git(["status", "--porcelain"], check=False)
        return bool(r.stdout.strip())

    # ------------------------------------------------------------------
    # plan building
    # ------------------------------------------------------------------

    def rel(self, path: Path) -> str:
        try:
            return path.relative_to(self.repo).as_posix()
        except ValueError:
            return str(path)

    def add_move(
        self,
        src_rel: str,
        dst_rel: str,
        reason: str,
        replacements: list | None = None,
        create_init: bool = False,
        reexport_module: str = "",
    ) -> None:
        src = self.repo / src_rel
        if not src.exists():
            return

        dst = self.repo / dst_rel
        conflict = dst.exists()

        action = Action(
            kind="move",
            src=src_rel.replace("\\", "/"),
            dst=dst_rel.replace("\\", "/"),
            reason=reason,
            tracked=self.is_tracked(src_rel),
            ignored=self.is_ignored(src_rel),
            conflict=conflict,
            replacements=replacements or [],
            create_init=create_init,
            reexport_module=reexport_module,
            status="skipped-conflict" if conflict else "planned",
        )
        self.actions.append(action)

        if replacements:
            for old, new in replacements:
                pair = (old, new)
                if pair not in self.replacements:
                    self.replacements.append(pair)

    def add_review(self, src_rel: str, reason: str) -> None:
        src = self.repo / src_rel
        if not src.exists():
            return
        self.actions.append(
            Action(
                kind="review",
                src=src_rel.replace("\\", "/"),
                reason=reason,
                tracked=self.is_tracked(src_rel),
                ignored=self.is_ignored(src_rel),
                status="review",
            )
        )

    def add_mkdir(self, dst_rel: str, reason: str) -> None:
        self.actions.append(
            Action(
                kind="mkdir",
                src="",
                dst=dst_rel.replace("\\", "/"),
                reason=reason,
                status="planned",
            )
        )

    def add_replacement(self, old: str, new: str) -> None:
        pair = (old, new)
        if pair not in self.replacements:
            self.replacements.append(pair)

