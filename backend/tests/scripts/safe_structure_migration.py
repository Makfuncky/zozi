"""
safe_structure_migration.py

Safely migrate the ZOZI repository toward the planned target structure.

SAFETY MODEL
------------
1. Default mode is DRY-RUN.
2. No file is moved unless --apply is used.
3. A timestamped backup is created before applying moves.
4. Existing destination files are NOT overwritten by default.
5. Ambiguous code moves are NOT applied automatically unless explicitly approved.
6. The script can analyze and repair the .gitignore problem.
7. The script can force-add important ignored files so git push/pull does not lose them.

USAGE
-----
# 1. Dry run + analyze git + generate suggested domain map
python scripts/safe_structure_migration.py --dry-run --analyze-git --generate-domain-map

# 2. Inspect:
#    migration_reports/plan.md
#    migration_reports/plan.json
#    migration_reports/domain_map.json
#    migration_reports/ignored_important_files.txt
#    migration_reports/gitignore_analysis.md

# 3. Apply safe moves + fix git tracking
python scripts/safe_structure_migration.py \
    --apply \
    --analyze-git \
    --fix-gitignore \
    --overwrite-gitignore \
    --force-add-important \
    --stage-changes

# 4. Apply approved domain moves only after reviewing domain_map.json
python scripts/safe_structure_migration.py \
    --apply \
    --apply-mapping migration_reports/domain_map.json \
    --stage-changes

ROLLBACK
--------
If something goes wrong:

1. Restore from git backup branch created by this script:
   git branch --list "backup/pre-migration-*"

2. Restore from filesystem backup:
   .migration_backups/<timestamp>/

3. If you used --overwrite-gitignore, old .gitignore is saved as:
   .gitignore.bak.<timestamp>
"""

