    def generate_domain_map(self) -> None:
        entries = []
        backend = self.repo / "backend"

        layers = [
            ("services", "domain"),
            ("controllers", "mixed"),
            ("models", "domain"),
            ("routers", "surface"),
        ]

        for layer, mode in layers:
            base = backend / layer
            if not base.exists():
                continue

            for p in sorted(base.glob("*.py")):
                if p.name == "__init__.py":
                    continue

                stem = p.stem
                src_rel = self.rel(p)

                if mode == "surface":
                    sub = router_surface(stem)
                    dst_rel = f"backend/{layer}/{sub}/{p.name}"
                    reason = f"suggested surface grouping: {sub}"
                    reexport = False
                else:
                    domain = classify_domain(stem)
                    dst_rel = f"backend/{layer}/{domain}/{p.name}"
                    reason = f"suggested domain grouping: {domain}"
                    reexport = False

                    if layer == "models" and stem == domain:
                        reexport = True
                        reason += " (re-export __init__ recommended because module name becomes package name)"

                if (self.repo / dst_rel).exists():
                    continue

                entries.append(
                    {
                        "src": src_rel,
                        "dst": dst_rel,
                        "reason": reason,
                        "approved": False,
                        "create_init": True,
                        "reexport_init": reexport,
                    }
                )

        out = self.report_dir / "domain_map.json"
        out.write_text(json.dumps(entries, indent=2), encoding="utf-8")
        self.notes.append(f"Generated domain map: {out}")

    def apply_mapping_file(self, mapping_path: str) -> None:
        path = self.repo / mapping_path
        if not path.exists():
            print(f"[FATAL] Mapping file not found: {path}", file=sys.stderr)
            sys.exit(2)

        data = json.loads(path.read_text(encoding="utf-8"))
        for entry in data:
            if not entry.get("approved"):
                continue

            src = entry["src"]
            dst = entry["dst"]
            reason = entry.get("reason", "approved mapping")
            create_init = bool(entry.get("create_init", False))
            reexport_init = bool(entry.get("reexport_init", False))

            replacements = []
            reexport_module = ""

            if src.endswith(".py") and src.startswith("backend/") and dst.startswith("backend/"):
                old_mod = module_from_backend_path(src)
                new_mod = module_from_backend_path(dst)

                if old_mod and new_mod:
                    # For models where module name becomes package name, prefer re-export instead of rewrite.
                    if not reexport_init:
                        replacements = [
                            ("backend." + old_mod, "backend." + new_mod),
                            (old_mod, new_mod),
                        ]
                    else:
                        reexport_module = old_mod.rsplit(".", 1)[-1]

            self.add_move(
                src,
                dst,
                reason,
                replacements=replacements,
                create_init=create_init,
                reexport_module=reexport_module,
            )

