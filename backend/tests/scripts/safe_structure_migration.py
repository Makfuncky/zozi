    def backup_actions(self) -> None:
        move_actions = [a for a in self.actions if a.kind == "move" and a.status != "skipped-conflict"]
        if not move_actions:
            return

        self.backup_root.mkdir(parents=True, exist_ok=True)

        for a in move_actions:
            src = self.repo / a.src
            dst = self.backup_root / a.src

            if not src.exists():
                continue

            dst.parent.mkdir(parents=True, exist_ok=True)

            if src.is_dir():
                shutil.copytree(
                    src,
                    dst,
                    ignore=shutil.ignore_patterns(
                        "node_modules",
                        ".next",
                        ".expo",
                        "dist",
                        "build",
                        "coverage",
                        "__pycache__",
                        "playwright-report",
                        "test-results",
                        "test-output",
                        "web-dist",
                    ),
                    dirs_exist_ok=True,
                )
            else:
                shutil.copy2(src, dst)

        self.notes.append(f"Backup created at {self.rel(self.backup_root)}")

    # ------------------------------------------------------------------
    # apply moves
    # ------------------------------------------------------------------

    def ensure_init(self, dir_path: Path, reexport_module: str = "") -> None:
        rel_dir = self.rel(dir_path)
        if not rel_dir.startswith("backend/"):
            return

        parts = {x.lower() for x in dir_path.relative_to(self.repo).parts}
        if {"scripts", "tests", "tools", "docs", "monitoring", "var", "static", "log"} & parts:
            return

        init = dir_path / "__init__.py"
        if init.exists():
            return

        if reexport_module:
            init.write_text(
                f"from .{reexport_module} import *  # created by safe_structure_migration.py\n",
                encoding="utf-8",
            )
        else:
            init.write_text("", encoding="utf-8")

    def move_path(self, a: Action) -> None:
        src = self.repo / a.src
        dst = self.repo / a.dst

        if not src.exists():
            a.status = "missing"
            return

        if dst.exists():
            a.status = "skipped-conflict"
            return

        dst.parent.mkdir(parents=True, exist_ok=True)

        try:
            if src.is_file():
                if a.tracked and self.git_ok:
                    self.git(["mv", "--", a.src, a.dst])
                else:
                    shutil.move(src, dst)

                # remove empty source parent
                try:
                    if src.parent.exists() and not any(src.parent.iterdir()):
                        src.parent.rmdir()
                except Exception:
                    pass

                if a.create_init:
                    self.ensure_init(dst.parent, a.reexport_module)

                a.status = "moved"

            elif src.is_dir():
                dst.mkdir(parents=True, exist_ok=True)

                for child in src.rglob("*"):
                    if child.is_file():
                        rel_child = self.rel(child)
                        child_dst = dst / child.relative_to(src)
                        child_dst.parent.mkdir(parents=True, exist_ok=True)

                        if self.is_tracked(rel_child) and self.git_ok:
                            self.git(["mv", "--", rel_child, self.rel(child_dst)])
                        else:
                            shutil.move(child, child_dst)

                shutil.rmtree(src, ignore_errors=True)

                if a.create_init:
                    self.ensure_init(dst, a.reexport_module)

                a.status = "moved"

        except Exception as exc:
            a.status = "error"
            a.error = str(exc)

    def apply_actions(self) -> None:
        # mkdir first
        for a in self.actions:
            if a.kind != "mkdir":
                continue
            dst = self.repo / a.dst
            dst.mkdir(parents=True, exist_ok=True)
            a.status = "created"

        # moves
        for a in self.actions:
            if a.kind != "move":
                continue
            if a.status == "skipped-conflict":
                continue
            self.move_path(a)

    def stage_changes(self) -> None:
        if not self.git_ok:
            return

        staged = []
        for a in self.actions:
            if a.kind == "move" and a.status == "moved" and a.dst:
                staged.append(a.dst)
            if a.kind == "mkdir" and a.status == "created" and a.dst:
                staged.append(a.dst)

        batch = []
        for p in staged:
            batch.append(p)
            if len(batch) >= 100:
                self.git(["add", "--"] + batch, check=False)
                batch = []

        if batch:
            self.git(["add", "--"] + batch, check=False)

        self.notes.append("Staged moved/created paths.")

    # ------------------------------------------------------------------
    # import replacement
    # ------------------------------------------------------------------

    def iter_py_files(self) -> Iterable[Path]:
        for root, dirs, files in os.walk(self.repo):
            root_path = Path(root)

            dirs[:] = [
                d for d in dirs
                if d.lower() not in GENERATED_DIR_NAMES
                and not d.startswith(".migration_")
                and d != "migration_reports"
            ]

            for f in files:
                if f.endswith(".py"):
                    yield root_path / f

    def replace_imports(self, apply: bool) -> None:
        if not self.replacements:
            return

        replacements = sorted(self.replacements, key=lambda x: len(x[0]), reverse=True)
        report = {}

        for py in self.iter_py_files():
            try:
                text = py.read_text(encoding="utf-8", errors="replace")
            except Exception:
                continue

            lines = text.splitlines(keepends=True)
            changed = False

            for i, line in enumerate(lines):
                if "import" not in line:
                    continue

                new_line = line
                for old, new in replacements:
                    pattern = re.compile(r"(?<![\w.])" + re.escape(old) + r"(?![\w.])")
                    if pattern.search(new_line):
                        new_line = pattern.sub(new, new_line)
                        changed = True

                lines[i] = new_line

            if changed:
                report[self.rel(py)] = "would-update" if not apply else "updated"
                if apply:
                    py.write_text("".join(lines), encoding="utf-8")

        out = self.report_dir / "import_rewrites.json"
        out.write_text(json.dumps(report, indent=2), encoding="utf-8")
        self.notes.append(f"Import rewrite report: {self.rel(out)}")

