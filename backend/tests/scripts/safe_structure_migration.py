    parser.add_argument("--fix-gitignore", action="store_true", help="write .gitignore.safe template")
    parser.add_argument("--overwrite-gitignore", action="store_true", help="overwrite .gitignore with safe template when --apply")
    parser.add_argument("--force-add-important", action="store_true", help="force-add important ignored files")
    parser.add_argument("--stage-changes", action="store_true", help="stage moved/created files after apply")
    parser.add_argument("--backup", dest="backup", action="store_true", default=True, help="backup moved files before apply")
    parser.add_argument("--no-backup", dest="backup", action="store_false", help="disable backup")
    parser.add_argument("--move-backend-code", action="store_true", help="enable known backend code moves")
    parser.add_argument("--generate-domain-map", action="store_true", help="generate suggested domain_map.json")
