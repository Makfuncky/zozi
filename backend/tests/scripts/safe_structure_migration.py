    def detect_broad_gitignore_patterns(self) -> list[str]:
        gi = self.repo / ".gitignore"
        if not gi.exists():
            return []

        dangerous = []
        broad = {
            "backend", "backend/", "frontend", "frontend/", "documents", "documents/",
            "scripts", "scripts/", "tests", "tests/", "*.py", "*.ts", "*.tsx",
            "*.js", "*.md", "*.txt",
        }

        for line in gi.read_text(encoding="utf-8", errors="replace").splitlines():
            s = line.strip()
            if not s or s.startswith("#"):
                continue
            if s in broad:
                dangerous.append(s)

        return dangerous

    def write_gitignore_template(self, overwrite: bool) -> None:
        gi = self.repo / ".gitignore"

        if overwrite and gi.exists():
            if not self.args.apply:
                self.notes.append("Would overwrite .gitignore with safe template because --overwrite-gitignore was given, but --apply is missing.")
                return

            backup = self.repo / f".gitignore.bak.{self.stamp}"
            shutil.copy2(gi, backup)
            gi.write_text(SAFE_GITIGNORE, encoding="utf-8")
            self.notes.append(f"Overwrote .gitignore with safe template. Old file saved as {self.rel(backup)}")
        else:
            safe = self.repo / ".gitignore.safe"
            safe.write_text(SAFE_GITIGNORE, encoding="utf-8")
            self.notes.append(f"Wrote safe gitignore template to {self.rel(safe)}. Review and replace .gitignore manually or use --overwrite-gitignore --apply.")

    def analyze_git(self) -> None:
        if not self.git_ok:
            self.notes.append("Git repository not detected; skipping git analysis.")
            return

        # Ignored important files
        r = self.git(["ls-files", "--others", "--ignored", "--exclude-standard"], check=False)
        ignored = []
        for line in r.stdout.splitlines():
            p = line.strip()
            if not p:
                continue

            if any(part.lower() in GENERATED_DIR_NAMES for part in Path(p).parts):
                continue

            if is_secret_file(p):
                continue

            if not p.startswith(("documents/", "scripts/", "backend/", "frontend/")):
                continue

            suffix = Path(p).suffix.lower()
            if suffix not in IMPORTANT_SUFFIXES:
                continue

            ignored.append(p)

            if len(ignored) >= 20000:
                break

        out = self.report_dir / "ignored_important_files.txt"
        out.write_text("\n".join(ignored), encoding="utf-8")
        self.notes.append(f"Found {len(ignored)} ignored important files. See {self.rel(out)}")

        # Gitignore analysis
        broad = self.detect_broad_gitignore_patterns()
        md = ["# Gitignore Analysis", ""]
        if broad:
            md.append("## DANGEROUS broad patterns detected")
            md.append("")
            md.append("These patterns can hide source code/docs/scripts from git and cause loss on clone/pull.")
            md.append("")
            for b in broad:
                md.append(f"- `{b}`")
        else:
            md.append("No obviously dangerous broad .gitignore patterns detected.")

        nested = []
        for root, dirs, files in os.walk(self.repo):
            dirs[:] = [d for d in dirs if d.lower() not in GENERATED_DIR_NAMES]
            if ".gitignore" in files:
                rel = self.rel(Path(root) / ".gitignore")
                if rel != ".gitignore":
                    nested.append(rel)

        md.append("")
        md.append("## Nested .gitignore files")
        md.append("")
        if nested:
            for n in nested:
                md.append(f"- `{n}`")
        else:
            md.append("No nested .gitignore files detected.")

        (self.report_dir / "gitignore_analysis.md").write_text("\n".join(md), encoding="utf-8")

    def force_add_important(self, apply: bool) -> None:
        if not self.git_ok:
            self.notes.append("Git repository not detected; cannot force-add important files.")
            return

        files: list[str] = []

        for root, dirs, filenames in os.walk(self.repo):
            root_path = Path(root)
            rel_root = self.rel(root_path)

            dirs[:] = [
                d for d in dirs
                if d.lower() not in GENERATED_DIR_NAMES
                and not d.startswith(".migration_")
                and d != ".archive"
            ]

            for filename in filenames:
                p = root_path / filename
                rel_path = self.rel(p)

                if is_secret_file(rel_path):
                    continue

                suffix = p.suffix.lower()
                if suffix not in IMPORTANT_SUFFIXES:
                    continue

                # Only important top areas
                if not rel_path.startswith(("documents/", "scripts/", "backend/", "frontend/")):
                    continue

                # Do not add runtime artifact dirs
                if "/var/" in rel_path or rel_path.startswith("backend/var/"):
                    continue

                files.append(rel_path)

        out = self.report_dir / "force_add_important.txt"
        out.write_text("\n".join(files), encoding="utf-8")
        self.notes.append(f"Important files candidate count: {len(files)}. See {self.rel(out)}")

        if not apply:
            return

        batch = []
        for f in files:
            batch.append(f)
            if len(batch) >= 100:
                self.git(["add", "-f", "--"] + batch, check=False)
                batch = []

        if batch:
            self.git(["add", "-f", "--"] + batch, check=False)

        self.notes.append("Force-added important ignored files.")

