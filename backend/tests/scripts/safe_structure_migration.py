    # reports
    # ------------------------------------------------------------------

    def write_reports(self) -> None:
        plan_json = self.report_dir / "plan.json"
        plan_json.write_text(json.dumps([asdict(a) for a in self.actions], indent=2), encoding="utf-8")

        md = []
        md.append("# Safe Structure Migration Plan")
        md.append("")
        md.append(f"Generated: {datetime.datetime.now().isoformat()}")
        md.append(f"Repo: `{self.repo}`")
        md.append(f"Mode: {'APPLY' if self.args.apply else 'DRY-RUN'}")
        md.append("")
        md.append("## Notes")
        md.append("")
        if self.notes:
            for n in self.notes:
                md.append(f"- {n}")
        else:
            md.append("- none")
        md.append("")

        md.append("## Actions")
        md.append("")
        md.append("| Status | Kind | Source | Destination | Reason | Tracked | Ignored | Conflict | Error |")
        md.append("|---|---|---|---|---|---|---|---|---|")

        for a in self.actions:
            reason = a.reason.replace("|", "/")
            error = a.error.replace("|", "/")
            md.append(
                f"| {a.status} | {a.kind} | `{a.src}` | `{a.dst}` | {reason} | "
                f"{a.tracked} | {a.ignored} | {a.conflict} | {error} |"
            )

        md.append("")
        md.append("## Import replacements")
        md.append("")
        if self.replacements:
            md.append("| Old module | New module |")
            md.append("|---|---|")
            for old, new in sorted(self.replacements):
                md.append(f"| `{old}` | `{new}` |")
        else:
            md.append("No import replacements registered.")

        plan_md = self.report_dir / "plan.md"
        plan_md.write_text("\n".join(md), encoding="utf-8")

    # ------------------------------------------------------------------
    # run
    # ------------------------------------------------------------------

    def preflight(self) -> None:
        if self.args.apply:
            if not self.git_ok and not self.args.no_git:
                print("[FATAL] Git repository not detected. Use --no-git to override (not recommended).", file=sys.stderr)
                sys.exit(2)

            if self.git_ok and self.git_status_dirty() and not self.args.allow_dirty:
                print("[FATAL] Git working tree is dirty. Commit/stash first or use --allow-dirty.", file=sys.stderr)
                sys.exit(2)

            if self.git_ok:
                branch = f"backup/pre-migration-{self.stamp}"
                self.git(["branch", branch], check=False)
                self.notes.append(f"Created backup branch: {branch}")

    def run(self) -> None:
        self.preflight()

        self.build_plan()

        if self.args.generate_domain_map:
            self.generate_domain_map()

        if self.args.apply_mapping:
            self.apply_mapping_file(self.args.apply_mapping)

        if self.args.analyze_git:
            self.analyze_git()

        if self.args.fix_gitignore:
            self.write_gitignore_template(overwrite=False)

        if self.args.overwrite_gitignore:
            self.write_gitignore_template(overwrite=True)

        self.write_reports()

        if self.args.apply:
            if self.args.backup:
                self.backup_actions()

            self.apply_actions()
            self.replace_imports(apply=True)

            if self.args.force_add_important:
                self.force_add_important(apply=True)

            if self.args.stage_changes:
                self.stage_changes()

            self.write_reports()
            print(f"[OK] Migration applied. Reports: {self.report_dir}")
        else:
            self.replace_imports(apply=False)

            if self.args.force_add_important:
                self.force_add_important(apply=False)

            print(f"[DRY-RUN] No files were moved. Reports: {self.report_dir}")


