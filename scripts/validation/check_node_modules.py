"""Check node_modules for intact package information"""
import pathlib
import json

nm = pathlib.Path('f:/recovery_recuva_4/Projects/10- E-COMMERCE WEBSITE/zozi/frontend/web_app/node_modules')

check_packages = ['next', 'react', 'react-dom', 'typescript', 'tailwindcss', 
                  '@stripe/stripe-js', 'zustand', 'framer-motion', 'lucide-react',
                  '@radix-ui/react-dialog', 'axios', 'swr', 'zod']

print('=== KEY NODE PACKAGES STATUS ===')
for pkg in check_packages:
    pjson = nm / pkg / 'package.json'
    if pjson.exists():
        data = pjson.read_bytes()
        is_null = all(b == 0 for b in data[:50]) if data else True
        if not is_null:
            try:
                info = json.loads(data.decode('utf-8', errors='replace'))
                ver = info.get('version', '?')
                print(f'  {pkg}: v{ver} OK')
            except Exception:
                print(f'  {pkg}: readable but json error')
        else:
            print(f'  {pkg}: NULL bytes')
    else:
        print(f'  {pkg}: NOT FOUND')

# Count all readable package.json files  
print()
all_pjson = list(nm.glob('*/package.json'))
readable = []
for f in all_pjson:
    try:
        data = f.read_bytes()
        if data and not all(b == 0 for b in data[:50]):
            readable.append(f)
    except Exception:
        pass

print(f'Total direct packages: {len(all_pjson)}, readable: {len(readable)}')
print()

# Show all readable package versions
print('=== ALL READABLE PACKAGES ===')
packages = {}
for f in readable:
    try:
        info = json.loads(f.read_text(encoding='utf-8', errors='replace'))
        name = info.get('name', f.parent.name)
        ver = info.get('version', '?')
        packages[name] = ver
    except Exception:
        pass

for name, ver in sorted(packages.items()):
    print(f'  {name}: {ver}')
