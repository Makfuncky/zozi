// scripts/generate-permissions.mjs
// Generates frontend/shared/src/permissions.ts from the backend /rbac/catalog
// endpoint. Run via: node scripts/generate-permissions.mjs
// Or wire into CI: npm run generate:permissions

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const API_BASE = process.env.NEXT_PUBLIC_API_URL || "http://127.0.0.1:8000";
const OUTPUT = join(__dirname, "..", "frontend", "shared", "src", "permissions.ts");

async function main() {
  const url = `${API_BASE}/api/v1/rbac/catalog`;
  console.log(`Fetching feature catalog from ${url} ...`);
  const resp = await fetch(url, { headers: { Accept: "application/json" } });
  if (!resp.ok) {
    throw new Error(`Catalog fetch failed: ${resp.status} ${resp.statusText}`);
  }
  const data = await resp.json();
  const features = Object.keys(data.features || data.FEATURE_CATALOG || data || {});
  if (features.length === 0) {
    throw new Error("Catalog response has no features array");
  }
  const ts = `/**
 * AUTO-GENERATED by scripts/generate-permissions.mjs
 * Source: GET ${url}
 * Do not edit by hand — re-run the script.
 * Generated: ${new Date().toISOString()}
 */

export const FEATURE_CATALOG: readonly string[] = Object.freeze([
${features.map((f) => `  ${JSON.stringify(f)},`).join("\n")}
]);

export type Feature = (typeof FEATURE_CATALOG)[number];

export const FEATURE_SET: ReadonlySet<Feature> = new Set(FEATURE_CATALOG);

export function isKnownFeature(f: string): f is Feature {
  return FEATURE_SET.has(f as Feature);
}

/** Grouped by namespace (e.g. "catalog.list" → "catalog") for UI tree-building. */
export const FEATURE_GROUPS: Record<string, Feature[]> = {};
for (const f of FEATURE_CATALOG) {
  const ns = f.split(".")[0];
  if (!FEATURE_GROUPS[ns]) FEATURE_GROUPS[ns] = [];
  FEATURE_GROUPS[ns].push(f);
}
`;
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, ts, "utf-8");
  console.log(`Wrote ${features.length} features to ${OUTPUT}`);
}

main().catch((err) => {
  console.error("Generation failed:", err);
  process.exit(1);
});
