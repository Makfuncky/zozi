#!/usr/bin/env node
// scripts/generate-permissions.mjs
// Pulls the live /api/v1/rbac/catalog from a running backend and writes a
// typed TypeScript module at src/shared/permissions.gen.ts exposing the
// `feature_list`, `features` map, and `namespaces`. Run with `npm run openapi:gen`
// (or directly). If the backend is unreachable, an empty fallback is emitted
// and the runtime `fetchRbacCatalog()` will populate the cache on app boot.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");

const baseUrl = (process.env.NEXT_PUBLIC_API_URL || "http://127.0.0.1:8000").replace(/\/$/, "");
const out = path.join(ROOT, "..", "shared", "src", "permissions.ts");

async function fetchCatalog() {
  const url = `${baseUrl}/api/v1/rbac/catalog`;
  process.stdout.write(`[rbac] GET ${url} ... `);
  const res = await fetch(url, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

function emit(catalog) {
  const features = catalog?.features ?? {};
  const namespaces = catalog?.namespaces ?? [];
  const featureList = catalog?.feature_list ?? [];

  const featuresJson = JSON.stringify(features, null, 2);
  const namespacesJson = JSON.stringify(namespaces, null, 2);
  const featureListJson = JSON.stringify(featureList, null, 2);

  return `// AUTO-GENERATED by scripts/generate-permissions.mjs — do not edit by hand.
// Source: GET /api/v1/rbac/catalog from ${baseUrl}
// Re-generate via: npm run openapi:gen
export const BUILD_TIME_FEATURES: Readonly<Record<string, string>> = ${featuresJson};
export const BUILD_TIME_NAMESPACES: ReadonlyArray<string> = ${namespacesJson};
export const BUILD_TIME_FEATURE_LIST: ReadonlyArray<string> = ${featureListJson};
`;
}

async function main() {
  try {
    const catalog = await fetchCatalog();
    fs.writeFileSync(out, emit(catalog), "utf8");
    process.stdout.write(`OK (${catalog?.feature_list?.length ?? 0} features) -> ${path.relative(ROOT, out)}\n`);
  } catch (err) {
    process.stdout.write(`FAIL (${err?.message || err}); emitting empty fallback\n`);
    fs.writeFileSync(
      out,
      `// AUTO-GENERATED empty fallback — backend was unreachable at build time.
export const BUILD_TIME_FEATURES: Readonly<Record<string, string>> = {};
export const BUILD_TIME_NAMESPACES: ReadonlyArray<string> = [];
export const BUILD_TIME_FEATURE_LIST: ReadonlyArray<string> = [];
`,
      "utf8",
    );
  }
}

main();